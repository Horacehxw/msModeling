"""Generate communication-operator microbenchmark scripts.

Generates torch.distributed scripts for HCCL communication benchmarking:
- all_reduce, all_gather, all_to_all
- Controls rank_group for topology_tier testing
- Uses torch.npu.Event for precise GPU timing

Design doc reference: S6.3 (Communication Microbenchmark)
"""

import argparse
import json
import sys
from pathlib import Path
from textwrap import dedent
from typing import List

WARMUP_ITERS = 10
BENCH_ITERS = 100

_COMM_OPS = ["all_reduce", "all_gather", "reduce_scatter", "all_to_all"]

_DEFAULT_BYTES_GRID = [
    1024, 4096, 16384, 65536, 262144,
    1048576, 4194304, 16777216, 67108864, 268435456,
]


def generate_comm_script(
    op_type: str,
    message_bytes: int,
    num_devices: int,
    dtype: str = "torch.bfloat16",
) -> str:
    """Generate a communication benchmark script.

    Args:
        op_type: Communication operation (all_reduce, all_gather, all_to_all, reduce_scatter)
        message_bytes: Total message size in bytes
        num_devices: Number of devices in the group
        dtype: Tensor dtype string
    """
    # Calculate tensor elements from bytes (BF16 = 2 bytes per element)
    elem_size = 2  # bfloat16
    num_elements = message_bytes // elem_size

    op_call = _get_op_call(op_type)

    script = dedent(f"""\
        #!/usr/bin/env python3
        \"\"\"Auto-generated communication microbenchmark script.

        Op: {op_type}
        Message bytes: {message_bytes}
        Num devices: {num_devices}
        Generated by: tools/perf_data_collection/generate_comm_microbench.py
        \"\"\"

        import os
        import time

        import torch
        import torch.distributed as dist

        try:
            import torch_npu  # noqa: F401
            BACKEND = "hccl"
            DEVICE = "npu"
        except ImportError:
            BACKEND = "gloo"
            DEVICE = "cpu"
            print("WARNING: torch_npu not available, using gloo/CPU")

        WARMUP_ITERS = {WARMUP_ITERS}
        BENCH_ITERS = {BENCH_ITERS}
        MESSAGE_BYTES = {message_bytes}
        NUM_ELEMENTS = {num_elements}
        NUM_DEVICES = {num_devices}


        def setup():
            \"\"\"Initialize distributed process group.\"\"\"
            rank = int(os.environ.get("RANK", 0))
            world_size = int(os.environ.get("WORLD_SIZE", 1))

            if DEVICE == "npu":
                torch.npu.set_device(rank % torch.npu.device_count())

            dist.init_process_group(
                backend=BACKEND,
                rank=rank,
                world_size=world_size,
            )
            return rank, world_size


        def create_rank_group(ranks):
            \"\"\"Create a process group from rank list for topology_tier testing.\"\"\"
            return dist.new_group(ranks=ranks)


        def bench_comm(rank, world_size):
            \"\"\"Benchmark {op_type} with {{MESSAGE_BYTES}} bytes on {{NUM_DEVICES}} devices.\"\"\"
            dtype = {dtype}

            # Create rank group (use all ranks by default)
            group_ranks = list(range(min(NUM_DEVICES, world_size)))
            group = create_rank_group(group_ranks)

            if rank not in group_ranks:
                print(f"Rank {{rank}} not in group, skipping")
                return

    """)

    script += _indent(op_call, 8)

    script += dedent(f"""\

            # Warmup
            for _ in range(WARMUP_ITERS):
                run_op()
            if DEVICE == "npu":
                torch.npu.synchronize()

            # Benchmark
            if DEVICE == "npu":
                torch.npu.synchronize()
            start = time.perf_counter()
            for _ in range(BENCH_ITERS):
                run_op()
            if DEVICE == "npu":
                torch.npu.synchronize()
            elapsed = time.perf_counter() - start

            duration_us = elapsed / BENCH_ITERS * 1e6
            bandwidth_gbps = MESSAGE_BYTES / (duration_us * 1e-6) / 1e9

            if rank == 0:
                print(f"Op: {op_type}")
                print(f"message_bytes: {{MESSAGE_BYTES}}")
                print(f"num_devices: {{len(group_ranks)}}")
                print(f"Duration(us): {{duration_us:.2f}}")
                print(f"bandwidth_gbps: {{bandwidth_gbps:.2f}}")


        def main():
            rank, world_size = setup()
            try:
                bench_comm(rank, world_size)
            finally:
                dist.destroy_process_group()


        if __name__ == "__main__":
            main()
    """)
    return script


def _get_op_call(op_type: str) -> str:
    """Generate the operation-specific tensor creation and call code."""
    if op_type == "all_reduce":
        return dedent("""\
            tensor = torch.randn(NUM_ELEMENTS, dtype=dtype, device=DEVICE)

            def run_op():
                dist.all_reduce(tensor, group=group)
        """)
    elif op_type == "all_gather":
        return dedent("""\
            local_tensor = torch.randn(NUM_ELEMENTS, dtype=dtype, device=DEVICE)
            gather_list = [torch.empty_like(local_tensor) for _ in group_ranks]

            def run_op():
                dist.all_gather(gather_list, local_tensor, group=group)
        """)
    elif op_type == "reduce_scatter":
        return dedent("""\
            input_list = [torch.randn(NUM_ELEMENTS, dtype=dtype, device=DEVICE) for _ in group_ranks]
            output_tensor = torch.empty(NUM_ELEMENTS, dtype=dtype, device=DEVICE)

            def run_op():
                dist.reduce_scatter(output_tensor, input_list, group=group)
        """)
    elif op_type == "all_to_all":
        return dedent("""\
            per_rank = NUM_ELEMENTS // len(group_ranks)
            input_list = [torch.randn(per_rank, dtype=dtype, device=DEVICE) for _ in group_ranks]
            output_list = [torch.empty(per_rank, dtype=dtype, device=DEVICE) for _ in group_ranks]

            def run_op():
                dist.all_to_all(output_list, input_list, group=group)
        """)
    else:
        raise ValueError(f"Unknown op_type: {op_type}")


def _indent(text: str, spaces: int) -> str:
    """Indent each line of text by the given number of spaces."""
    prefix = " " * spaces
    return "\n".join(prefix + line if line.strip() else line for line in text.splitlines()) + "\n"


def build_argparser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Generate communication-operator microbenchmark scripts."
    )
    parser.add_argument(
        "--output-dir",
        required=True,
        help="Directory to write benchmark scripts",
    )
    parser.add_argument(
        "--num-devices",
        type=int,
        nargs="+",
        default=[8, 16],
        help="Number of devices to test (default: 8 16)",
    )
    parser.add_argument(
        "--ops",
        nargs="+",
        default=["all_reduce", "all_gather"],
        choices=_COMM_OPS,
        help="Communication ops to benchmark",
    )
    return parser


def main() -> None:
    args = build_argparser().parse_args()

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    count = 0

    for op_type in args.ops:
        for num_devices in args.num_devices:
            for msg_bytes in _DEFAULT_BYTES_GRID:
                script = generate_comm_script(op_type, msg_bytes, num_devices)
                fname = f"comm_{op_type}_B{msg_bytes}_D{num_devices}.py"
                (output_dir / fname).write_text(script)
                count += 1

    print(f"Generated {count} communication benchmark scripts in {output_dir}")


if __name__ == "__main__":
    main()
