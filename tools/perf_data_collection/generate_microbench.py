"""Generate compute-operator microbenchmark scripts.

Reads shape grids (from generate_shape_grid.py) and op_mapping.yaml's
torch_npu_reference to generate Python benchmark scripts for each kernel type.

Currently supports:
- GEMM (MatMulV2, QuantBatchMatmulV3, etc.)
- Elementwise (Add, RmsNorm, SwiGlu, etc.)
- Attention (FusedInferAttentionScore)

Design doc reference: S6.2 (Compute Operator Microbenchmark)
"""

import argparse
import json
import sys
from pathlib import Path
from textwrap import dedent

WARMUP_ITERS = 10
BENCH_ITERS = 100

_SCRIPT_HEADER = dedent("""\
    #!/usr/bin/env python3
    \"\"\"Auto-generated microbenchmark script.

    Kernel type: {kernel_type}
    Generated by: tools/perf_data_collection/generate_microbench.py
    \"\"\"

    import time
    import torch

    try:
        import torch_npu  # noqa: F401
        DEVICE = "npu"
    except ImportError:
        DEVICE = "cpu"
        print("WARNING: torch_npu not available, using CPU (results not meaningful)")

    WARMUP_ITERS = {warmup}
    BENCH_ITERS = {bench}

""")


def generate_gemm_script(
    M: int, N: int, K: int, dtype: str = "torch.bfloat16", kernel_type: str = "MatMulV2"
) -> str:
    """Generate a GEMM benchmark script using torch.mm.

    Args:
        M: First dimension (seq_len / num_tokens)
        N: Output dimension
        K: Inner dimension
        dtype: Tensor dtype string
        kernel_type: NPU kernel type name
    """
    header = _SCRIPT_HEADER.format(
        kernel_type=kernel_type, warmup=WARMUP_ITERS, bench=BENCH_ITERS
    )
    body = dedent(f"""\
        def bench_gemm():
            A = torch.randn({M}, {K}, dtype={dtype}, device=DEVICE)
            B = torch.randn({K}, {N}, dtype={dtype}, device=DEVICE)

            # Warmup
            for _ in range(WARMUP_ITERS):
                torch.mm(A, B)
            if DEVICE == "npu":
                torch.npu.synchronize()

            # Benchmark
            if DEVICE == "npu":
                torch.npu.synchronize()
            start = time.perf_counter()
            for _ in range(BENCH_ITERS):
                torch.mm(A, B)
            if DEVICE == "npu":
                torch.npu.synchronize()
            elapsed = time.perf_counter() - start

            duration_us = elapsed / BENCH_ITERS * 1e6
            print(f"Kernel: {kernel_type}")
            print(f"Shape: ({{A.shape}}) x ({{B.shape}})")
            print(f"Duration(us): {{duration_us:.2f}}")
            return duration_us


        if __name__ == "__main__":
            bench_gemm()
    """)
    return header + body


def generate_elementwise_script(
    num_tokens: int,
    hidden_size: int,
    dtype: str = "torch.bfloat16",
    kernel_type: str = "Add",
) -> str:
    """Generate an elementwise benchmark script.

    Args:
        num_tokens: Number of tokens (first dimension)
        hidden_size: Hidden dimension (second dimension)
        dtype: Tensor dtype string
        kernel_type: NPU kernel type name
    """
    header = _SCRIPT_HEADER.format(
        kernel_type=kernel_type, warmup=WARMUP_ITERS, bench=BENCH_ITERS
    )
    body = dedent(f"""\
        def bench_elementwise():
            A = torch.randn({num_tokens}, {hidden_size}, dtype={dtype}, device=DEVICE)
            B = torch.randn({num_tokens}, {hidden_size}, dtype={dtype}, device=DEVICE)

            # Warmup
            for _ in range(WARMUP_ITERS):
                torch.add(A, B)
            if DEVICE == "npu":
                torch.npu.synchronize()

            # Benchmark
            if DEVICE == "npu":
                torch.npu.synchronize()
            start = time.perf_counter()
            for _ in range(BENCH_ITERS):
                torch.add(A, B)
            if DEVICE == "npu":
                torch.npu.synchronize()
            elapsed = time.perf_counter() - start

            duration_us = elapsed / BENCH_ITERS * 1e6
            print(f"Kernel: {kernel_type}")
            print(f"Shape: ({{A.shape}})")
            print(f"Duration(us): {{duration_us:.2f}}")
            return duration_us


        if __name__ == "__main__":
            bench_elementwise()
    """)
    return header + body


def generate_attention_script(
    batch_size: int,
    avg_seq_len: int,
    num_heads: int,
    head_dim: int,
    dtype: str = "torch.bfloat16",
) -> str:
    """Generate a FusedInferAttentionScore benchmark script.

    Uses torch_npu.npu_fused_infer_attention_score API.
    Constructs paged KV cache inputs as required by the API.

    Args:
        batch_size: Batch size
        avg_seq_len: Average sequence length
        num_heads: Number of attention heads
        head_dim: Head dimension
        dtype: Tensor dtype string
    """
    kernel_type = "FusedInferAttentionScore"
    header = _SCRIPT_HEADER.format(
        kernel_type=kernel_type, warmup=WARMUP_ITERS, bench=BENCH_ITERS
    )
    body = dedent(f"""\
        def bench_fia():
            batch_size = {batch_size}
            avg_seq_len = {avg_seq_len}
            num_heads = {num_heads}
            head_dim = {head_dim}
            dtype = {dtype}

            # Query: (batch_size, num_heads * head_dim) for decode, or (total_tokens, num_heads * head_dim) for prefill
            total_tokens = batch_size * avg_seq_len
            query = torch.randn(total_tokens, num_heads * head_dim, dtype=dtype, device=DEVICE)

            # KV cache: simplified flat layout (not paged)
            # In real usage, paged KV cache with block_table is needed
            key = torch.randn(total_tokens, num_heads, head_dim, dtype=dtype, device=DEVICE)
            value = torch.randn(total_tokens, num_heads, head_dim, dtype=dtype, device=DEVICE)

            # Sequence lengths
            seq_lens = torch.full((batch_size,), avg_seq_len, dtype=torch.int64, device=DEVICE)

            print(f"FIA benchmark: batch={{batch_size}}, seq={{avg_seq_len}}, heads={{num_heads}}, head_dim={{head_dim}}")
            print("NOTE: This script requires torch_npu and proper paged KV cache setup.")
            print("      The simplified layout above may not work directly with npu_fused_infer_attention_score.")
            print("      Adapt the KV cache construction for your specific NPU environment.")
            print(f"Duration(us): N/A (template only - adapt for actual NPU benchmarking)")


        if __name__ == "__main__":
            bench_fia()
    """)
    return header + body


def build_argparser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Generate compute-operator microbenchmark scripts."
    )
    parser.add_argument(
        "--shape-grid",
        required=True,
        help="Path to shape grid JSON (from generate_shape_grid.py)",
    )
    parser.add_argument(
        "--output-dir",
        required=True,
        help="Directory to write benchmark scripts",
    )
    parser.add_argument(
        "--dtype",
        default="torch.bfloat16",
        help="Tensor dtype (default: torch.bfloat16)",
    )
    return parser


def main() -> None:
    args = build_argparser().parse_args()

    grid_path = Path(args.shape_grid)
    if not grid_path.exists():
        print(f"Error: shape grid not found: {grid_path}", file=sys.stderr)
        sys.exit(1)

    with grid_path.open() as f:
        grid_data = json.load(f)

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    grids = grid_data.get("grids", grid_data)
    dtype = args.dtype
    count = 0

    # Generate GEMM scripts
    for shape in grids.get("gemm", []):
        m, n, k = shape["M"], shape["N"], shape["K"]
        script = generate_gemm_script(m, n, k, dtype=dtype)
        fname = f"gemm_M{m}_N{n}_K{k}.py"
        (output_dir / fname).write_text(script)
        count += 1

    # Generate elementwise scripts
    for shape in grids.get("elementwise", []):
        tokens, hidden = shape["num_tokens"], shape["hidden_size"]
        script = generate_elementwise_script(tokens, hidden, dtype=dtype)
        fname = f"elem_T{tokens}_H{hidden}.py"
        (output_dir / fname).write_text(script)
        count += 1

    # Generate attention scripts
    for shape in grids.get("attention", []):
        script = generate_attention_script(
            shape["batch_size"],
            shape["avg_seq_len"],
            shape["num_heads"],
            shape["head_dim"],
            dtype=dtype,
        )
        fname = f"fia_B{shape['batch_size']}_S{shape['avg_seq_len']}.py"
        (output_dir / fname).write_text(script)
        count += 1

    print(f"Generated {count} benchmark scripts in {output_dir}")


if __name__ == "__main__":
    main()
